// Helper to infer and guarantee rich default flavor tags
export const inferDefaultFlavorTags = (dish: DishItem): string[] => {
  if (dish.flavorTags && dish.flavorTags.length > 0) return dish.flavorTags;
  const tags: string[] = [];
  const text = (dish.name + ' ' + (dish.description || '') + ' ' + (dish.category || '')).toLowerCase();
  if (text.includes('和牛') || text.includes('汉堡') || text.includes('wagyu')) {
    tags.push('炙烤焦香', '鲜嫩多汁', '黑松露香');
  } else if (text.includes('羊肉') || text.includes('孜然') || text.includes('lamb')) {
    tags.push('炭火微焦', '孜然飘香', '鲜嫩多汁');
  } else if (text.includes('猪') || text.includes('五花') || text.includes('pork') || text.includes('肠')) {
    tags.push('果木熏香', '外酥里嫩', '蜜汁回甘');
  } else if (text.includes('虾') || text.includes('海鲜') || text.includes('扇贝') || text.includes('生蚝') || text.includes('oyster') || text.includes('scallop')) {
    tags.push('蒜香扑鼻', '原汁原味', '弹牙爽脆');
  } else if (text.includes('芝士') || text.includes('焗') || text.includes('cheese')) {
    tags.push('奶香浓郁', '芝士拉丝', '金黄酥脆');
  } else if (text.includes('烧鸟') || text.includes('京葱') || text.includes('yakitori') || text.includes('鸡')) {
    tags.push('居酒屋经典', '外酥里嫩', '甜咸适口');
  } else if (text.includes('辣') || text.includes('椒') || text.includes('川香')) {
    tags.push('麻辣鲜香', '青花藤椒', '下酒绝配');
  } else if (text.includes('咖啡') || text.includes('冷萃') || text.includes('coffee') || text.includes('茶') || text.includes('汁')) {
    tags.push('原汁原味', '低卡轻食', '招牌必点');
  } else if (text.includes('甜') || text.includes('蛋糕') || text.includes('米苏')) {
    tags.push('入口即化', '甜咸适口', '奶香浓郁');
  } else {
    tags.push('炙烤焦香', '主厨秘配', '鲜嫩多汁');
  }
  return tags;
};

